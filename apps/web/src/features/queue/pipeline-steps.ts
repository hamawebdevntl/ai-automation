import type { ProductionRow, ProductionStatus, RewindStep } from '@/lib/database.types';

/**
 * What the pipeline does after Gate 1, expressed for a person.
 *
 * This is a deliberate mirror of `GRAPH` in
 * `apps/pipeline/pipeline/driver/graph.py`, and it is a mirror of the *step
 * names* rather than of `productions.stage`. That distinction is the whole
 * design of this file. `stage` is unconstrained free text -- `render 42%`,
 * `fal generating (kling)`, `presenter rendered`, `checked` -- written by
 * whichever activity happened to be running, with no check constraint behind
 * it. Building a timeline on it would mean string-matching a value nobody
 * promised to keep stable. `run_state.step` is a closed set of twelve names
 * that the driver cannot leave, so it is what decides where a production is;
 * `stage` is only ever shown as a live sub-label.
 *
 * Pure functions on purpose, like `features/trends/controls.ts`: what a
 * production is doing, and which controls are legal, are both easy to get
 * subtly wrong and impossible to check by looking at the page.
 *
 * The control predicates below are a copy of the guards in
 * `20260907150000_production_visibility.sql`, and the copy is for feedback
 * only -- so the owner sees *why* something is unavailable instead of being
 * refused after clicking. Postgres is what actually enforces them.
 */

/** A step as the driver knows it. Mirrors the keys of `GRAPH`. */
export type GraphStep =
  | 'write_script'
  /** The uploaded lane's only step of its own. Everything after it is shared. */
  | 'check_upload'
  | 'open_script_gate'
  | 'await_script'
  | 'submit_render'
  | 'poll_render'
  | 'fetch_and_qc'
  | 'generate_copy'
  | 'open_gate2'
  | 'await_gate2'
  | 'publish'
  | 'poll_publish'
  | 'published'
  | 'rejected'
  | 'parked'
  | 'cancelled'
  | 'publishing_disabled';

/** `START` in graph.py: a row with no step yet has not begun this one.
 *
 * This moved when the script gate landed. A production no longer opens by
 * spending money — it opens by drafting words for a person to read, and
 * `resume_step()` in Postgres carries the same default. If the three ever
 * disagree, a fresh row is sent to the wrong step. */
export const FIRST_STEP: GraphStep = 'write_script';

/**
 * Where an uploaded cut starts instead.
 *
 * `create_upload_production` writes this into `run_state.step` at insert, so
 * unlike `FIRST_STEP` it is never actually reached as a default — it is here so
 * that a row which somehow arrived without a step is placed at its own lane's
 * first step rather than at a render it must never reach.
 */
export const FIRST_UPLOAD_STEP: GraphStep = 'check_upload';

export const TERMINAL_STEPS = [
  'published',
  'rejected',
  'parked',
  'cancelled',
  'publishing_disabled',
] as const satisfies readonly GraphStep[];

export type TerminalStep = (typeof TERMINAL_STEPS)[number];

export function isTerminalStep(step: string): step is TerminalStep {
  return (TERMINAL_STEPS as readonly string[]).includes(step);
}

export type StepState =
  /** Not reached yet. */
  | 'pending'
  /** The worker is on it now. */
  | 'active'
  /** Reached, and waiting on something outside the pipeline — a person. */
  | 'waiting'
  | 'done'
  | 'failed'
  /** Reached, and deliberately not done. Publishing being switched off. */
  | 'skipped';

export type StepKey = 'queued' | 'uploaded' | 'script' | 'render' | 'check' | 'copy' | 'gate2' | 'publish' | 'done';

export interface PipelineStep {
  key: StepKey;
  label: string;
  /** One line saying what happens here, shown under the label. */
  description: string;
  /** The driver steps this one covers. */
  graphSteps: readonly GraphStep[];
  /** True where the pipeline stops for a person rather than for a machine. */
  isGate?: boolean;
}

