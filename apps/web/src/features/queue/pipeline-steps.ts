export type ControlAction = 'pause' | 'resume' | 'retry' | 'cancel' | 'rerun' | 'rewind';

export interface ControlAvailability {
  enabled: boolean;
  /** Why not, in words the owner can act on. Null when enabled. */
  reason: string | null;
}

const BUSY = 'The worker is running a step right now. This is available again in a moment.';

export function availableControls(production: ProductionLike): Record<ControlAction, ControlAvailability> {
  const paused = isPaused(production);
  const leased = isLeased(production);
  const finished = isFinished(production);
  const stopped = isStopped(production);
  const superseded = production.superseded_by !== null;
  const renderInFlight = isRenderInFlight(production);

  const ok: ControlAvailability = { enabled: true, reason: null };
  const no = (reason: string): ControlAvailability => ({ enabled: false, reason });

  return {
    pause: superseded
      ? no('This production was superseded by a re-run.')
      : paused
        ? no('Already paused.')
        : finished || production.status === 'failed'
          ? no('This production has finished.')
          : ok,

    resume: !paused ? no('This production is not paused.') : leased ? no(BUSY) : ok,

    retry: superseded
      ? no('This production was superseded by a re-run.')
      : !stopped
        ? no('Only a stopped production can be retried.')
        : leased
          ? no(BUSY)
          : ok,

    cancel: superseded
      ? no('This production was superseded by a re-run.')
      : finished
        ? no('This production has already finished.')
        : renderInFlight
          ? no(
              'A render is still running and has already been billed for. Wait for it to finish or stop, or pause it instead.',
            )
          : leased
            ? no(BUSY)
            : ok,

    rerun:
      production.source === 'upload'
        ? no(
            'This is an uploaded cut, so there is nothing to make again. Upload the video again to put a new one through Gate 2.',
          )
        : superseded
          ? no('This production has already been re-run.')
          : !canRerun(production)
            ? no('This production is still running. Cancel it first, or wait for it to finish.')
            : leased
              ? no(BUSY)
              : ok,

    rewind: superseded
      ? no('This production was superseded by a re-run.')
      : rewindableSteps(production).length === 0
        ? no('There is nothing to redo yet — this production has no finished cut.')
        : leased
          ? no(BUSY)
          : ok,
  };
}

function canRerun(production: ProductionLike): boolean {
  const finishedStatuses: readonly ProductionStatus[] = ['parked', 'cancelled', 'rejected', 'published', 'failed'];
  if (finishedStatuses.includes(production.status)) return true;
  return production.status === 'approved' && isHeldForPublishing(production);
}

/**
 * The steps this production has the artifacts to redo.
 *
 * `submit_render` is never among them: a fresh render costs money and belongs
 * to `rerun_production`, which opens a new row rather than overwriting the cut
 * that is already there.
 */
export function rewindableSteps(production: ProductionLike): RewindStep[] {
  const steps: RewindStep[] = [];
  if (production.task_id !== null) steps.push('fetch_and_qc');
  if (production.video_url !== null) steps.push('generate_copy', 'open_gate2');
  return steps;
}

export const REWIND_LABELS: Record<RewindStep, string> = {
  fetch_and_qc: 'Re-check the render',
  generate_copy: 'Rewrite the platform copy',
  open_gate2: 'Re-open Gate 2',
};

export const REWIND_DESCRIPTIONS: Record<RewindStep, string> = {
  fetch_and_qc: 'Download the existing render again and run the quality check over it. Costs nothing.',
  generate_copy: 'Throw away the current per-platform copy and write it again.',
  open_gate2: 'Clear the Gate 2 decision and put the cut back in front of a reviewer.',
};
