type ProductionLike = Pick<
  ProductionRow,
  | 'source'
  | 'status'
  | 'stage'
  | 'run_state'
  | 'error'
  | 'task_id'
  | 'video_url'
  | 'paused_at'
  | 'superseded_by'
  | 'lease_expires_at'
  | 'created_at'
  | 'updated_at'
>;

function runState(production: ProductionLike): Record<string, unknown> {
  return (production.run_state ?? {}) as Record<string, unknown>;
}

function readString(state: Record<string, unknown>, key: string): string | null {
  const value = state[key];
  return typeof value === 'string' && value ? value : null;
}

/** The step a row with none yet is treated as being at. */
function firstStepFor(production: Pick<ProductionLike, 'source'>): GraphStep {
  return production.source === 'upload' ? FIRST_UPLOAD_STEP : FIRST_STEP;
}

/** Where the driver has this row now. */
export function currentGraphStep(production: ProductionLike): GraphStep {
  return (readString(runState(production), 'step') as GraphStep | null) ?? firstStepFor(production);
}

/**
 * The step a stopped production stopped on.
 *
 * A terminal overwrites `run_state.step` with its own name, so a parked row
 * says only "parked". `previous_step` is written by the engine before it
 * enters a terminal precisely so this question has an answer -- without it the
 * timeline could not place a failure, and neither could `retry_production`.
 */
export function stoppedAtStep(production: ProductionLike): GraphStep {
  const state = runState(production);
  const step = currentGraphStep(production);
  if (!isTerminalStep(step)) return step;
  return (readString(state, 'previous_step') as GraphStep | null) ?? firstStepFor(production);
}

/** Has the worker actually started on this row, or is it still waiting? */
export function hasStarted(production: ProductionLike): boolean {
  return readString(runState(production), 'step') !== null;
}

/**
 * How long a fresh row may sit untouched before that means something.
 *
 * The dispatcher polls every `driver_poll_seconds` — five by default — so a
 * row that nothing has claimed after this long is not "about to start". It is
 * evidence that no worker is running, and the UI has to say so rather than
 * promise a start that is not coming. Found the hard way: two approved ideas
 * sat at "Starting… within a few seconds" for hours while no worker existed.
 */
export const WORKER_GRACE_MS = 30_000;

/**
 * Approved, opened, and never picked up.
 *
 * The production equivalent of `isUnclaimed` for trend runs. A queued row with
 * no step whose `created_at` is past the grace has been waiting on a worker
 * that has not come, and nothing on the row will change until one does.
 */
export function isUnclaimed(production: ProductionLike, now: number = Date.now()): boolean {
  if (production.status !== 'queued' || production.paused_at !== null) return false;

  // An uploaded cut cannot be recognised by having no step: it is inserted
  // *with* one, because `create_upload_production` puts it at `check_upload`
  // rather than letting it default into the render lane. So the marker is
  // different — still queued, still at its own first step, and not currently
  // held by a worker.
  //
  // Measured from `updated_at` rather than `created_at`, and this is the part
  // that has to be right: the check itself legitimately runs for minutes on a
  // large file, and a worker holds an hour's lease while it does. Reading
  // `created_at` would call every slow upload abandoned.
  if (production.source === 'upload') {
    if (currentGraphStep(production) !== FIRST_UPLOAD_STEP) return false;
    if (isLeased(production, now)) return false;
    const touched = production.updated_at || production.created_at;
    if (!touched) return false;
    return now - new Date(touched).getTime() > WORKER_GRACE_MS;
  }

  if (hasStarted(production)) return false;
  if (!production.created_at) return false;
  return now - new Date(production.created_at).getTime() > WORKER_GRACE_MS;
}

export function isPaused(production: ProductionLike): boolean {
  return production.paused_at !== null;
}

/** The worker is holding this row right now, so its state is about to change. */
export function isLeased(production: ProductionLike, now: number = Date.now()): boolean {
  if (!production.lease_expires_at) return false;
  return new Date(production.lease_expires_at).getTime() > now;
}

/**
 * A render that may already have been billed for.
 *
 * `task_id` is set by `claim_render_slot` at the moment of submitting, so it
 * is exactly the marker for "money may be moving". This is why cancel is
 * refused here -- see `cancel_production`.
 */
export function isRenderInFlight(production: ProductionLike): boolean {
  if (production.task_id === null) return false;
  const step = currentGraphStep(production);
  return step === 'submit_render' || step === 'poll_render' || step === 'fetch_and_qc';
}

/** Finished, one way or another. Nothing more happens without a person. */
export function isFinished(production: ProductionLike): boolean {
  const step = currentGraphStep(production);
  if (step === 'published' || step === 'rejected' || step === 'cancelled') return true;
  return production.status === 'published' || production.status === 'rejected' || production.status === 'cancelled';
}

export function isStopped(production: ProductionLike): boolean {
  return production.status === 'parked' || production.status === 'failed';
}

/**
 * Held rather than failed.
 *
 * `publishing_disabled` keeps `status = 'approved'` on purpose, so these rows
 * are a queryable backlog holding a finished cut and its copy. Showing it as a
 * failure would be wrong in the one way that matters: it would suggest
 * something needs fixing.
 */
export function isHeldForPublishing(production: ProductionLike): boolean {
  return currentGraphStep(production) === 'publishing_disabled';
}

export function isAtGate2(production: ProductionLike): boolean {
  return production.status === 'awaiting_review' || production.status === 'qc_failed';
}

/**
 * Stopped at the script gate, waiting for a person to approve the words.
 *
 * Reads the status rather than the step, for the same reason `isAtGate2` does:
 * the status is what `claim_production` filters on, so it is the fact that
 * actually decides whether the driver will touch this row.
 */
export function isAtScriptGate(production: ProductionLike): boolean {
  return production.status === 'awaiting_script';
}

/**
 * Whether the script is still an input to anything.
 *
 * A copy of `script_is_editable` in the script-gate migration, and a copy for
 * feedback only — Postgres refuses the write regardless. `task_id` is the
 * load-bearing half: it is set at the instant of submitting to a render
 * backend, so once it exists the words have been paid for and editing them
 * would only make the record wrong.
 */
export function isScriptEditable(production: ProductionLike): boolean {
  if (production.superseded_by !== null) return false;
  if (production.task_id !== null) return false;
  const step = currentGraphStep(production);
  if (step !== 'write_script' && step !== 'open_script_gate' && step !== 'await_script') return false;
  return (
    production.status === 'queued' ||
    production.status === 'running' ||
    production.status === 'awaiting_script' ||
    production.status === 'parked' ||
    production.status === 'failed'
  );
}

/** Why the script cannot be edited, in words an owner can act on. */
export function scriptLockReason(production: ProductionLike): string | null {
  if (isScriptEditable(production)) return null;
  if (production.superseded_by !== null) {
    return 'This production was re-run. Edit the script on the one that replaced it.';
  }
  if (production.task_id !== null) {
    return 'The render has already been submitted and paid for against these words. Make the idea again to change them.';
  }
  return 'This production is past the script gate, so its script is no longer an input to anything.';
}

