// The timeline
// ---------------------------------------------------------------------------

export interface TimelineStep extends PipelineStep {
  state: StepState;
}

export function buildTimeline(production: ProductionLike): TimelineStep[] {
  const steps = pipelineStepsFor(production);
  const step = currentGraphStep(production);
  const terminal = isTerminalStep(step);
  const position = stepIndexOf(terminal ? stoppedAtStep(production) : step, steps);
  const stopped = isStopped(production);
  const held = isHeldForPublishing(production);
  const started = hasStarted(production);
  const paused = isPaused(production);

  return steps.map((pipelineStep, index) => ({
    ...pipelineStep,
    state: stateFor({ pipelineStep, index, position, terminal, stopped, held, started, paused, production, step }),
  }));
}

function stateFor(args: {
  pipelineStep: PipelineStep;
  index: number;
  position: number;
  terminal: boolean;
  stopped: boolean;
  held: boolean;
  started: boolean;
  paused: boolean;
  production: ProductionLike;
  step: GraphStep;
}): StepState {
  const { pipelineStep, index, position, terminal, stopped, held, started, paused, production, step } = args;

  // The last step is where a production ends up, so it is only ever reached.
  if (pipelineStep.key === 'done') {
    if (step === 'published') return 'done';
    if (step === 'cancelled' || step === 'rejected') return 'failed';
    if (held) return 'skipped';
    if (stopped) return 'failed';
    return 'pending';
  }

  // The first step of either lane is the only one that is complete before the
  // driver has touched the row: Gate 1 has already happened, or the file has
  // already been uploaded.
  if (pipelineStep.key === 'queued') {
    return started || terminal ? 'done' : 'active';
  }
  // An upload's first row is done the moment the row exists — the file is in
  // the bucket before `create_upload_production` will open one, so unlike a
  // queued production there is nothing still to arrive.
  if (pipelineStep.key === 'uploaded') return 'done';

  if (index < position) return 'done';

  if (index === position) {
    if (stopped) return 'failed';
    if (step === 'cancelled') return 'failed';
    // `held` is deliberately not a case here. A production only reaches
    // `publishing_disabled` by passing Gate 2 -- `_gate2_outcome` routes there
    // when the status is `approved` -- so the step it is resting on was
    // completed, and it is only what comes *after* it that is skipped.
    if (paused) return 'waiting';
    // A gate with its decision still outstanding is waiting on a person, which
    // is not the same as the machine working. Both gates read their status
    // rather than their step: the status is what the claim query filters on,
    // so it is what decides whether anything is actually going to happen.
    if (pipelineStep.key === 'gate2' && isAtGate2(production)) return 'waiting';
    if (pipelineStep.key === 'script' && isAtScriptGate(production)) return 'waiting';
    return terminal ? 'done' : 'active';
  }

  // Publishing is switched off, so everything past the gate is deliberately
  // not going to happen rather than merely not having happened yet.
  if (held && pipelineStep.key === 'publish') return 'skipped';
  return 'pending';
}

// ---------------------------------------------------------------------------
// Saying it in a sentence
// ---------------------------------------------------------------------------

export interface ProductionVerdict {
  headline: string;
  detail: string | null;
  /** Drives the badge colour. */
  tone: 'working' | 'waiting' | 'good' | 'bad' | 'held';
}

export function describeProduction(production: ProductionLike, now: number = Date.now()): ProductionVerdict {
  const step = currentGraphStep(production);
  const stage = production.stage?.trim() || null;

  if (production.superseded_by) {
    return {
      headline: 'Superseded',
      detail: 'This production was re-run. A newer one replaced it.',
      tone: 'held',
    };
  }
  if (production.status === 'cancelled') {
    return { headline: 'Cancelled', detail: 'An owner stopped this production.', tone: 'bad' };
  }
  if (isStopped(production)) {
    return {
      headline: 'Stopped — needs you',
      detail: production.error ?? 'The pipeline stopped and is waiting for a person.',
      tone: 'bad',
    };
  }
  if (isHeldForPublishing(production)) {
    return {
      headline: 'Held — publishing is off',
      detail: 'The cut and its per-platform copy are ready. Nothing is wrong; publishing is switched off.',
      tone: 'held',
    };
  }
  if (production.status === 'published') {
    return { headline: 'Published', detail: 'This production is finished.', tone: 'good' };
  }
  if (production.status === 'rejected') {
    return { headline: 'Rejected at Gate 2', detail: 'Nothing was published.', tone: 'bad' };
  }
  if (isPaused(production)) {
    return {
      headline: 'Paused',
      detail: isRenderInFlight(production)
        ? 'Paused by an owner. The render already running at the provider carries on — pausing does not stop it.'
        : 'Paused by an owner. Nothing runs until it is resumed.',
      tone: 'waiting',
    };
  }
  if (isAtScriptGate(production)) {
    return {
      headline: 'Script — waiting for you',
      detail:
        'The narration is drafted. Read it, edit it if you want to, and approve it — nothing renders until you do.',
      tone: 'waiting',
    };
  }
  if (isAtGate2(production)) {
    return {
      headline: production.status === 'qc_failed' ? 'Gate 2 — quality check failed' : 'Gate 2 — waiting for you',
      detail:
        production.status === 'qc_failed'
          ? 'The cut is ready but failed its quality check. You can still approve it.'
          : 'The finished cut is waiting for your sign-off.',
      tone: 'waiting',
    };
  }
  if (isUnclaimed(production, now)) {
    return {
      headline: 'Waiting for a worker',
      detail:
        production.source === 'upload'
          ? 'The file is uploaded, but no pipeline worker has picked it up to check it. The worker is probably not running — nothing here changes until it is.'
          : 'Approved, but no pipeline worker has picked this up. The worker is probably not running — nothing here changes until it is.',
      tone: 'waiting',
    };
  }
  if (!hasStarted(production)) {
    return {
      headline: 'Starting',
      detail: 'Approved. A worker picks this up within a few seconds.',
      tone: 'working',
    };
  }

  const steps = pipelineStepsFor(production);
  const label = steps[stepIndexOf(step, steps)]?.label ?? 'Working';
  return { headline: label, detail: stage, tone: 'working' };
}

/** Render progress, 0-100, when the backend reports it. */
export function renderProgress(production: ProductionLike): number | null {
  const value = runState(production).progress;
  if (typeof value !== 'number' || Number.isNaN(value)) return null;
  return Math.max(0, Math.min(100, value));
}

